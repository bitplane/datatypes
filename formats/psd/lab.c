static uint8_t encode(double linear)
{
    unsigned low = 0, high = 255;
    while (low < high) {
        unsigned mid = (low + high) / 2u;
        if (linear < srgb_step[mid])
            high = mid;
        else
            low = mid + 1u;
    }
    return (uint8_t)low;
}

static double unf(double t)
{
    double cube = t * t * t;
    return cube > 216.0 / 24389.0 ? cube : (116.0 * t - 16.0) * 27.0 / 24389.0;
}

void lab_to_srgb(double l, double a, double b, uint8_t rgb[3])
{
    double fy = (l + 16.0) / 116.0;
    double x = 0.96422 * unf(fy + a / 500.0);
    double y = l > 8.0 ? fy * fy * fy : l * 27.0 / 24389.0;
    double z = 0.82521 * unf(fy - b / 200.0);
    /* Bradford D50 to D65, folded into the XYZ to linear sRGB matrix. */
    rgb[0] = encode(3.1338561 * x - 1.6168667 * y - 0.4906146 * z);
    rgb[1] = encode(-0.9787684 * x + 1.9161415 * y + 0.0334540 * z);
    rgb[2] = encode(0.0719453 * x - 0.2289914 * y + 1.4052427 * z);
}
